"""Rebuild the Apsi-written module files that are plain data from Apsi's own tables:
lib/physics/constants.apsi (the physical constants, with their units).  python -m apsi.aot.gen_libs"""
import os
from fractions import Fraction

LIB = os.path.join(os.path.dirname(__file__), "lib")
BASE = ("m", "kg", "s", "A", "K", "mol", "cd")


def _unit(dim):
    parts = []
    for name, e in zip(BASE, dim):
        e = Fraction(e)
        if e == 0:
            continue
        parts.append(name if e == 1 else f"{name}^{e.numerator}" if e.denominator == 1 else f"{name}^({e})")
    return "*".join(parts)


def main():
    from ..interpreter import Interpreter
    from ..units import Quantity
    mods = Interpreter().modules
    out = ["# generated by apsi/aot/gen_libs.py from Apsi's constants table: do not edit"]
    for k, v in mods["physics.constants"].items():
        if isinstance(v, Quantity):
            out.append(f"let {k} = {float(v.v)!r}[{_unit(v.dim)}] * 1")
        elif isinstance(v, (int, float)):
            out.append(f"let {k} = {v!r}")
    os.makedirs(os.path.join(LIB, "physics"), exist_ok=True)
    with open(os.path.join(LIB, "physics", "constants.apsi"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
