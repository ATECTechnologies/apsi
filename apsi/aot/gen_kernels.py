"""Rebuild rt/kernels_ptx.h: the GPU kernels (rt/kernels.c) compiled by clang to PTX, as a C string.
Run after changing kernels.c:  python -m apsi.aot.gen_kernels"""
import os
import subprocess

RT = os.path.join(os.path.dirname(__file__), "rt")


def main():
    ptx = subprocess.run(["clang", "-target", "nvptx64-nvidia-cuda", "-march=sm_60", "-O3", "-S",
                          os.path.join(RT, "kernels.c"), "-o", "-"], check=True, capture_output=True,
                         text=True).stdout
    lines = ['/* generated by apsi/aot/gen_kernels.py from kernels.c: do not edit */',
             'static const char apsi_kernels_ptx[] =']
    for line in ptx.splitlines():
        lines.append('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
    lines[-1] += ";"
    with open(os.path.join(RT, "kernels_ptx.h"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
