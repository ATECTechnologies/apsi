"""Bundle the apsi package + examples into playground/apsi_bundle.js for the web playground.

    python tools/build_playground.py
Then serve the playground folder with any static web server, e.g.
    python -m http.server -d playground 8000
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_EXAMPLES = {"13_interop.apsi", "14_api_server.apsi", "15_native_c.apsi", "23_web_api.apsi",
                 "25_data_pipeline.apsi", "26_model_serving.apsi", "27_pretrained_models.apsi"}   # need host permissions


def main():
    files = {}
    pkg = os.path.join(ROOT, "apsi")
    for name in sorted(os.listdir(pkg)):
        if name.endswith(".py"):
            with open(os.path.join(pkg, name), encoding="utf-8") as fh:
                files["apsi/" + name] = fh.read()
    examples = {}
    exdir = os.path.join(ROOT, "examples")
    for name in sorted(os.listdir(exdir)):
        if name.endswith(".apsi") and name not in SKIP_EXAMPLES:
            with open(os.path.join(exdir, name), encoding="utf-8") as fh:
                examples[name] = fh.read()
    out = os.path.join(ROOT, "playground", "apsi_bundle.js")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// generated by tools/build_playground.py — do not edit\n")
        fh.write("window.APSI_BUNDLE = ")
        json.dump({"files": files, "examples": examples}, fh, ensure_ascii=False)
        fh.write(";\n")
    print(f"wrote {out} ({len(files)} modules, {len(examples)} examples)")


if __name__ == "__main__":
    main()
